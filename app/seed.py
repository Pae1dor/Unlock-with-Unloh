def _generate_qr(slug: str, payload: str) -> str:
    """Write a real scannable QR PNG into static/qr/ and return its web path."""
    QR_DIR.mkdir(parents=True, exist_ok=True)
    qr = qrcode.QRCode(version=None, box_size=8, border=2)
    qr.add_data(payload)
    qr.make(fit=True)
    image = qr.make_image(fill_color="#1B5E3A", back_color="white")
    filename = f"{slug}.png"
    image.save(QR_DIR / filename)
    return f"/static/qr/{filename}"


def seed() -> None:
    init_db()
    db = SessionLocal()
    now = datetime.now(timezone.utc)
    created = {"news": 0, "mosques": 0, "campaigns": 0}

    try:
        for item in NEWS_SEED:
            if db.scalar(select(News).where(News.slug == item["slug"])):
                continue
            db.add(
                News(
                    title=item["title"],
                    slug=item["slug"],
                    category=item["category"],
                    summary=item["summary"],
                    content=item["content"],
                    image_color=item["image_color"],
                    published_at=now - timedelta(days=item["days_ago"]),
                )
            )
            created["news"] += 1

        for item in MOSQUE_SEED:
            if db.scalar(select(Mosque).where(Mosque.name == item["name"])):
                continue
            db.add(Mosque(**item))
            created["mosques"] += 1

        for item in CAMPAIGN_SEED:
            existing = db.scalar(
                select(DonationCampaign).where(DonationCampaign.slug == item["slug"])
            )
            payload = (
                f"PROMPTPAY-DONATION|{item['name']}|"
                f"{item['bank_name']} {item['bank_account_number']} "
                f"({item['bank_account_name']})"
            )
            qr_path = _generate_qr(item["slug"], payload)
            if existing:
                # Keep the PNG on disk in sync even when the row already exists.
                existing.qr_payload = payload
                existing.qr_image_path = qr_path
                continue
            db.add(DonationCampaign(**item, qr_payload=payload, qr_image_path=qr_path))
            created["campaigns"] += 1

        db.commit()
    finally:
        db.close()

    print(
        f"Seed complete — news: +{created['news']}, "
        f"mosques: +{created['mosques']}, campaigns: +{created['campaigns']} "
        f"(existing rows were left untouched)"
    )


if __name__ == "__main__":
    seed()
